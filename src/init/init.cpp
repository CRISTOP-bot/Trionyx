int reportdfd = open("/dev/reportd", O_RDONLY | O_CLOEXEC);
void *reportdaemon(void *arg) {
    if (reportdfd < 0 || rlogfd < 0) {
        error(FATAL_ERR,
              "system-init: reportd: invalid file descriptor(log l/r "
              "device) for reportd.");
    }
    int flags = fcntl(reportdfd, F_GETFL, 0);
    fcntl(reportdfd, F_SETFL, flags | O_NONBLOCK);
    constexpr size_t BUFFER_SIZE = 8192;
    std::array<char, BUFFER_SIZE> io_buffer;
    while (InitStatus != false) {
        ssize_t bytes_read =
            read(reportdfd, io_buffer.data(), io_buffer.size());
        if (bytes_read > 0) {
            ssize_t bytes_written = 0;
            while (bytes_written < bytes_read) {
                ssize_t n = write(rlogfd, io_buffer.data() + bytes_written,
                                  bytes_read - bytes_written);
                if (n <= 0)
                    break;
                bytes_written += n;
            }
        } else if (bytes_read < 0) {
            if (errno == EAGAIN || errno == EWOULDBLOCK) {
                usleep(10000);
            } else if (errno == EINTR) {
                continue;
            } else {
                break;
            }
        } else {
            break;
        }
    }
    printk(KERN_INFO,
           "system-init: power OR reboot conditions ended the reportd log.\n");
    close(reportdfd);
    int src = open("/services/privatmp/reportd.log", O_RDONLY);
    int dst = open("/services/system-init/reportd.log.old",
                   O_WRONLY | O_CREAT | O_TRUNC, 0740);
    char copybuf[4096];
    ssize_t n;
    while ((n = read(src, copybuf, sizeof(copybuf))) > 0) {
        write(dst, copybuf, n);
    }
    close(src);
    close(dst);
    unlink("/services/privatmp/reportd.log");
    return nullptr;
}
void shtdwnload(const std::string &arg, int pid, int uid, int gid) {
    int status = 0;
    char ldsave_rr[16 * 16] = "/system/result_reason";
    writefd(1, "POWER DOWN\n");
    writefd(1, "SYNCING...\n");
    writefd(1, "RESULT REASON: %s", arg.c_str());
    writefd(1, "RESULT REASON FILE IS GOING TO BE SAVED IN %s", ldsave_rr);
    int fd = open(ldsave_rr, O_TRUNC | O_WRONLY | O_CREAT, 0655);
    if (fd == -1) {
        writefd(2, "ERROR: INVALID FILE DESCRIPTOR IN %s", ldsave_rr);
        status = 1;
    } else {
        writefd(1, "WRITING...");
        int fg = writefd(fd, "Reason: %s, PID: %d, U/G: %d:%d", arg.c_str(),
                         pid, uid, gid);
        if (fg < 0) {
            writefd(2, "ERROR: CAN'T WRITE RESULT REASON IN %s", ldsave_rr);
        } else {
            writefd(1, "WROTE RESULT REASON. CONTINUING WITH REBOOT!");
        }
    }
    if (status == 0) {
        close(fd);
    };
    writefd(1, "UMOUNTING ALL FILESYSTEMS...");
    writefd(1, "AFTER THIS, CHANGES IN THE SYSTEM CAN BE HARMFUL");
    sync();
    InitStatus = false;
    FILE *fm = fopen("/proc/mounts", "r");
    if (fm == nullptr) {
        return;
    }
    std::vector<std::string> mounts = {};
    char line[1024];
    char source[512];
    char target[512];
    while (fgets(line, sizeof(line), fm)) {
        if (sscanf(line, "%511s %511s", source, target) == 2) {
            mounts.push_back(target);
        } else {
            continue;
        }
    }
    for (int i = mounts.size() - 1; i >= 0; i--) {
        umount(mounts[i].c_str());
    }
    fclose(fm);
    kill(-1, SIGTERM);
    usleep(4000000);
    printk(KERN_INFO, "%s boot mode: SENDING SIGKILL TO ALL TASKS\n",
           arg.c_str());
    printk(KERN_WARNING, "GOING TO SIGKILL ALL!\n");
    kill(-1, SIGKILL);
    int w = mount(NULL, "/", NULL, MS_REMOUNT | MS_RDONLY, NULL);
    if (w <= -1) {
        printk(KERN_INFO, "FAILED TO REMOUNT ROOTFS IN READ-ONLY MODE.\n");
    } else {
        printk(KERN_INFO, "REMOUNT ROOTFS EXITED IN STATE %d", w);
    }
}
void *power(void *arg) {
    ipc ipc;
    int pwr;
    char addrpwr[200] = "/run/power.sock";
    ipc.open_socket(addrpwr, pwr);
    if (pwr < 0) {
        InitStatus = false;
        error(FATAL_ERR, "power: failed to open power socket \n");
        return nullptr;
    }
    while (InitStatus) {
        int cfd = accept(pwr, nullptr, nullptr);
        char buff[16 * 16];
        if (cfd == -1) {
            if (errno == EINTR) {
                break;
            }
            continue;
        }
        size_t readed = read(cfd, buff, sizeof(buff) - 1);
        buff[readed] = '\0';
        if (readed > 0) {
            printk(KERN_INFO, "power: fetched power request, size %d", readed);
            report("POWER", "Info: fetched request.");
            struct ucred creds;
            socklen_t len = sizeof(creds);
            getsockopt(cfd, SOL_SOCKET, SO_PEERCRED, &creds, &len);
            report("POWER", "Info: requester uid: %d, gid: %d and pid: %d",
                   creds.uid, creds.gid, creds.pid);
            if (creds.uid != 0) {
                write(cfd, "ERRMBR", 6);
                close(cfd);
                continue;
            }
            std::string msg = buff;
            char mode[40];
            char resultreason[400];
            sscanf(buff, "%s:%s", mode, resultreason);
            std::string mod = mode;
            if (mod == "POWEROFF") {
                writefd(cfd, "OK");
                report("POWER", "SYSTEM POWERING OFF");
                shtdwnload(mode, creds.pid, creds.uid, creds.gid);
                reboot(RB_POWER_OFF);
                printk(KERN_CRIT, "FATAL: CAN'T POWEROFF?\n");
                printk(KERN_CRIT, "ABORTING...\n");
                abort();
            } else if (mod == "REBOOT") {
                writefd(cfd, "OK");
                report("POWER", "SYSTEM REBOOTING");
                shtdwnload(mode, creds.pid, creds.uid, creds.gid);
                reboot(RB_AUTOBOOT);
                printk(KERN_CRIT, "FATAL: CAN'T REBOOT\n");
                printk(KERN_EMERG, "ABORTING\n");
                abort();
            } else if (mod == "HALT") {
                writefd(cfd, "OK");
                report("POWER", "SYSTEM HALTING\n");
                shtdwnload(mode, creds.pid, creds.uid, creds.gid);
                reboot(RB_HALT_SYSTEM);
                printk(KERN_EMERG, "CAN'T HALT.\n");
                printk(KERN_INFO, "DIY MODE: ON \n");
                printk(KERN_INFO, "Doing execve to sh...\n");
                const char *path = "/bin/sh";
                const char *interac = "-i";
                const char *env = "PATH=/system/bin:/system/sbin:/system/usr/"
                                  "sbin:/system/usr/bin";
                char *const argss[] = {const_cast<char *>(path),
                                       const_cast<char *>(interac), nullptr};
                char *const envs[] = {const_cast<char *>(env), nullptr};
                printk(KERN_INFO,
                       "WARNING: I think that rootfs is in ro mode, so you "
                       "only can see, or even do exit for kpanic\n");
                execve("/bin/sh", argss, envs);
                printk(KERN_EMERG, "shut... do you have sh?\n");
                printk(KERN_INFO,
                       "Uh... we are alone in the void! (im only with "
                       "kthreads, i think)\n");
                printk(KERN_INFO,
                       "tip: i think im about to cause a kernel panic\n");
                printk(KERN_INFO, "system-init: like Baruch Spinoza: \n");
                printk(KERN_INFO, "There isn't any vacuum in Nature... Nature "
                                  "abhors a vacuum.\n");
                usleep(500000);
                printk(KERN_INFO, "system-init: but like real life... all "
                                  "things need a end \n");
                printk(KERN_EMERG, "goodbye kmsg debugger...");
                usleep(700000);
                abort();
            } else if (mod == "KEXEC") {
                writefd(cfd, "OK");
                report("POWER", "DOING KEXEC");
                shtdwnload(mode, creds.pid, creds.uid, creds.gid);
                reboot(RB_KEXEC);
                abort();
            } else {
                writefd(cfd, "ER");
                printk(
                    KERN_INFO,
                    "system-init: dumb process: %d <- this guy tried to send a "
                    "unvalid power cmd.\n",
                    creds.pid);
            }
            close(cfd);
        } else {
            close(cfd);
        }
    }
    printk(KERN_INFO, "power thread: detected error and/or power conditions\n");
    close(pwr);
    printk(KERN_INFO, "power thread: closed file descriptor. \n");
    return nullptr;
}
