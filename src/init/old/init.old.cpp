class ipc {
  public:
    static void open_socket(const char *path, int &fd);
};

void ipc::open_socket(const char *path, int &fd) {
    fd = socket(AF_UNIX, SOCK_STREAM | SOCK_CLOEXEC, 0);
    if (fd == -1) {
        return;
    }
    unlink(path);
    struct sockaddr_un addr = {.sun_family = AF_UNIX};
    strncpy(addr.sun_path, path, sizeof(addr.sun_path) - 1);
    if (bind(fd, (struct sockaddr *)&addr, sizeof(addr)) == -1 ||
        listen(fd, 10) == -1) {
        close(fd);
        fd = -1;
    }
}
template <typename T>
auto vector_erase(std::vector<T> &vec, std::size_t index) -> bool {
    if (index >= vec.size()) {
        return false;
    }
    vec.erase(vec.begin() + index);
    return true;
}
auto relaunch(std::vector<std::string> &obj) -> std::vector<char *> {
    if (obj.empty()) {
        return {nullptr};
    }
    std::vector<char *> ret;
    ret.reserve(obj.size() + 1);
    for (size_t i = 0; i < obj.size(); i++) {
        ret.push_back(obj[i].data());
    }
    ret.push_back(nullptr);
    return ret;
}
auto service_children_host_daemons(std::vector<Data> &list) -> void {
    /* Trionyx Service Children Host Reaper (type: daemon)
     * Tip: this thread needs to:
     * in list, for list[i].pid that satisfaces the condition
     * list[i].mode == "daemon" needs ALL to be waited OR
     * RELAUNCHED.
     */

    sigset_t mask;
    signals sig;
    sigemptyset(&mask);
    sigaddset(&mask, SIGCHLD);
    if (pthread_sigmask(SIG_BLOCK, &mask, nullptr) != 0) {
        InitStatus = false;
        error(FATAL_ERR, "error: SYS: cant start schdr.\n");
    }
    opor_t current = list;
    while (InitStatus) {
        siginfo_t info{};
        if (sigwaitinfo(&mask, &info) == -1) {
            if (errno == EINTR) {
                continue;
            }
            printk(KERN_INFO, "system-init: sigwaitinfo error code %d: %s\n",
                   errno, std::strerror(errno));
            continue;
        }
        int status;
        pid_t pid;
        while ((pid = waitpid(-1, &status, WNOHANG)) > 0) {
            for (int i = 0; i < list.size(); i++) {
                if (list[i].pid == pid) {
                    if (list[i].mode == "ashot") {
                        if (WIFEXITED(status)) {
                            printk(KERN_INFO,
                                   "system-init: oneshot service %s exited\n",
                                   list[i].name.c_str());
                        } else if (WIFSIGNALED(status)) {
                            printk(KERN_INFO,
                                   "system-init: oneshot service %s signaled: "
                                   "%s\n",
                                   list[i].name.c_str(),
                                   sig.sigtostr(WTERMSIG(status)));
                        }
                        vector_erase(list, i);
                        i--;
                        continue;
                        continue;
                    } else if (list[i].mode == "daemon") {
                        if (WIFEXITED(status)) {
                            printk(KERN_INFO,
                                   "system-init: daemon service %s exited\n",
                                   list[i].name.c_str());
                            if (WEXITSTATUS(status) != 0 &&
                                !current.overpass(list[i].name)) {
                                service(list[i].exec, list[i].name,
                                        relaunch(list[i].args).data(),
                                        relaunch(list[i].envs).data(), "daemon",
                                        list);
                                current.add(list[i].name);
                            }
                            if (current.overpass(list[i].name) ||
                                WEXITSTATUS(status) == 0) {
                                printk(KERN_INFO,
                                       "system-init: daemon %s exited "
                                       "correctly/expired his opportunities. "
                                       "not relaunching\n",
                                       list[i].name.c_str());
                                vector_erase(list, i);
                                i--;
                                continue;
                            }
                        } else if (WIFSIGNALED(status)) {
                            printk(
                                KERN_INFO,
                                "system-init: daemon service %s signaled: %s\n",
                                list[i].name.c_str(),
                                sig.sigtostr(WTERMSIG(status)));
                            if (!current.overpass(list[i].name)) {
                                service(list[i].exec, list[i].name,
                                        relaunch(list[i].args).data(),
                                        relaunch(list[i].envs).data(), "daemon",
                                        list);
                                current.add(list[i].name);
                            } else {
                                printk(KERN_INFO,
                                       "system-init: signaled daemon %s wasted "
                                       "his opportunities\n",
                                       list[i].name.c_str());
                                vector_erase(list, i);
                                i--;
                                continue;
                            }
                        }
                    } else {
                        printk(
                            KERN_WARNING,
                            "system-init: unregistred entity ended. pid=%d\n",
                            pid);
                        continue;
                    }
                    continue;
                }
            }
            if (WIFEXITED(status)) {
                printk(KERN_DEBUG,
                       "system-init: exited process pid=%d, code=%d\n", pid,
                       WEXITSTATUS(status));
            } else if (WIFSIGNALED(status)) {
                printk(KERN_DEBUG,
                       "system-init: signaled process pid=%d, signal=%d, "
                       "sigtostr=%s\n",
                       pid, WTERMSIG(status), sig.sigtostr(WTERMSIG(status)));
            }
        }
        if (pid == 0) {
            continue;
        }
        if (pid == -1) {
            if (errno == EINTR) {
                continue;
            } else if (errno == ECHILD) {
                continue;
            }
        }
        printk(KERN_INFO, "system-init: waitpid error %d: %s\n", errno,
               std::strerror(errno));
    }
}
