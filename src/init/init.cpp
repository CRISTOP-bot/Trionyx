int __abi_mid() {
    if (_sgetprop("init.internal.__abi") != "premid") {
        return -1;
    }
    // now check for special device "/dev/reportd".
    try {
        int fd = open("/dev/reportd", O_RDONLY);
        if (fd < 0) {
            std::string message = std::format(
                "failed to open /dev/reportd: {}\n", std::strerror(errno));
            error(FATAL_ERR, message);
        }
        close(fd);
    } catch (...) {
        error(FATAL_ERR, "unknown error while checking /dev/reportd\n");
    }
    printk(KERN_INFO, "system-init: mid abi boot\n");
    // DUMPING verbose't info to the kmsg.
    printk(KERN_INFO, "system-init: daemon alive!\n");
    printk(KERN_INFO, "system-init: /dev/reportd as log syscall-provider to "
                      "internal report daemon\n");
    // now were getting kernek arch and kernel version.
    utsname unameData;
    if (uname(&unameData) == -1) {
        std::string message =
            std::format("failed to get uname data: {}\n", std::strerror(errno));
        error(WARN_ERR, message);
    } else {
        std::string kernelInfo =
            std::format("system-init: kernel {}\n", unameData.version);
        printk(KERN_INFO, kernelInfo);
    }
    // NOTE (PRELOAD);
    ssetprop("init.internal.__abi", "mid");
    return 0;
}
