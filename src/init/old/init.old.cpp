auto Init::doparse(const std::string &special, const std::string &dir, int mode,
                   int n, const std::string &options) -> int {
    const char *opts = options.empty() ? nullptr : options.c_str();
    switch (mode) {
    case DEV_MOUNT: {
        int status = mount(special.c_str(), dir.c_str(), special.c_str(),
                           MS_NOSUID | MS_NOEXEC | MS_NOATIME, nullptr);
        if (status != 0) {
            MountStatus[n].status = status;
        }
        MountStatus[n].path = dir;
        break;
    };
    case RES_MOUNT: {
        int status =
            mount(special.c_str(), dir.c_str(), special.c_str(),
                  MS_NOSUID | MS_NODEV | MS_NOEXEC | MS_NOATIME, nullptr);
        if (status != 0) {
            MountStatus[n].status = status;
        }
        MountStatus[n].path = dir;
        break;
    };
    case TMP_MOUNT: {
        int status = mount(special.c_str(), dir.c_str(), special.c_str(),
                           MS_NOSUID | MS_NODEV | MS_NOATIME, opts);
        if (status != 0) {
            MountStatus[n].status = status;
        }
        MountStatus[n].path = dir;
        break;
    };
    default:
        return -1;
        break;
    }
    return 0;
}
