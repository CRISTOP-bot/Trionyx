void preparefd(void) {
    int fd = open("/dev/console", O_RDWR);
    if (fd == -1) {
        fd = open("/dev/null", O_RDWR);
        if (fd == -1) {
            error(DEADLY_ERR, "");
        }
    }
    for (int i = 0; i < 3; i++) {
        close(i);
        dup2(fd, i);
    }
    if (fd > 2) {
        close(fd);
    }
}
int rfd = -1;
int report(const std::string &pfix, const std::string fmt, ...) {
    char buff[16 * 16 * 16];
    if (rfd == -1) {
        rfd = open("/dev/reportd", O_WRONLY);
    }
    va_list args;
    std::string newfmt = std::format("[{}]: {}\n", pfix, fmt);
    const char *format = newfmt.c_str();
    va_start(args, fmt);
    int n = vsnprintf(buff, sizeof(buff), format, args);
    if (n <= 0) {
        return -1;
    }
    int g = write(rfd, buff, (size_t)n);
    if (g == -1) {
        printk(KERN_INFO, "reportd: failed to write report with type \"%s\"",
               pfix.c_str());
        return -1;
    }
    va_end(args);
    return n;
}
