int error(int mode, const std::string &message) {
    switch (mode) {
    case NORMAL_ERR: // requires devtmpfs."mode=1777"
        if (printk(KERN_ERR, message) == 1) {
            return 1;
        }
        break;
    case FATAL_ERR: // requires devtmpfs, fatal.
        printk(KERN_EMERG, message);
        printk(KERN_EMERG, "alert: init process is hanging all");
        kill(-1, SIGTERM);
        sleep(2);
        kill(-1, SIGKILL);
        while (waitpid(-1, NULL, WNOHANG) > 0)
            ;
        printk(KERN_INFO, "info: now you can shutdown safely the system.");
        crash();
        break;
    case DEADLY_ERR: // very fatal error, does not require devtmpfs
        kill(-1, SIGTERM);
        usleep(5000000);
        kill(-1, SIGKILL);
        while (waitpid(-1, NULL, WNOHANG) > 0)
            ;
        reboot(RB_AUTOBOOT);
        crash();
        break;
    case WARN_ERR: // informative warning, requires devtmpfs.
        printk(KERN_WARNING, message);
        break;
    default:
        return 1;
    }
    return 0;
}
