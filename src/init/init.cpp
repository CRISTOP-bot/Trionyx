int lookint(int label, const std::vector<ParamServ> &ref,
            const std::string &prefix) {
    for (int i = 0; i < ref.size(); i++) {
        if (prefix == "mode" && ref[i].mode == label)
            return i;
        if (prefix == "pid" && ref[i].pid == label)
            return i;
    }
    return -1;
}
int lookstr(const std::string &str, const std::vector<ParamServ> &ref,
            int modmod) {
    for (int i = 0; i < ref.size(); i++) {
        if (modmod == EXEC) {
            if (ref[i].exec == str) {
                return i;
            }
        } else if (modmod == NAME) {
            if (ref[i].name == str) {
                return i;
            }
        }
    }
    return -1;
}
