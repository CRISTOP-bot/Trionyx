void preparefd() {
    int fd = open("/dev/console", O_RDWR);
    if (fd == -1) {
        fd = open("/dev/null", O_RDWR);
        if (fd == -1) {
            error(DEADLY_ERR, "");
        }
    }
    for (int i = 0; i < 3; i++) {
        close(i);
        dup2(fd, i);
    }
    if (fd > 2) {
        close(fd);
    }
}
