    mksecdir();
    doparse("devtmpfs", "/dev", DEV_MOUNT, DEVTMPFS, "");
    doparse("proc", "/proc", RES_MOUNT, PROC, "");
    doparse("sysfs", "/sys", RES_MOUNT, SYS, "");
    doparse("devpts", "/dev/pts", TMP_MOUNT, PTS,
            "gid=5,mode=620,ptmxmode=666");
    doparse("tmpfs", "/dev/shm", TMP_MOUNT, SHM, "mode=1777");
    doparse("cgroup2", "/sys/fs/cgroup", RES_MOUNT, CGPO, "");
    doparse("bpf", "/sys/fs/bpf", RES_MOUNT, BPF, "mode=0700");
    doparse("tmpfs", "/tmp", TMP_MOUNT, TMP, "mode=1777");
