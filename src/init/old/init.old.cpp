auto pkinit() -> int {
    if (kfd < 0) {
        kfd = open("/dev/kmsg", O_WRONLY | O_CLOEXEC);
        if (kfd < 0) {
            return -1;
        }
    }
    return 0;
}
auto printk(const std::string &mode, const char *msg, ...) -> int {
    if (kfd < 0) {
        pkinit();
    }
    const int tix = 2048;
    array<char, tix> buffer;
    array<char, tix> buffer2;
    va_list args;
    va_start(args, msg);
    int n = std::vsnprintf(buffer.data(), buffer.size(), msg, args);
    va_end(args);
    int m = snprintf(buffer2.data(), buffer2.size(), "%s%s", mode.c_str(),
                     buffer.data());
    if (n < 0) {
        return -1;
    }
    if (m > 0) {
        write(kfd, buffer2.data(), static_cast<size_t>(m));
    }
    if (m == 0) {
        m = -1;
    }
    return m;
}
