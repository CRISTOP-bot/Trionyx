int printk(const std::string &mode, const std::string msg, ...) {
    char buffer[4096];
    va_list args;
    va_start(args, msg);
    int n = std::vsnprintf(buffer, sizeof(buffer), msg.c_str(), args);
    va_end(args);
    if (n < 0) {
        return 1;
    }
    std::string message = mode + buffer;
    if (message.back() != '\n')
        message += '\n';
    long ret = syscall(SYS_SYSKP, message.c_str(), message.size());
    return ret < 0 ? 1 : 0;
}
