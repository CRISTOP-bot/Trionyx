int process(const std::string &prog, const std::vector<std::string> &argsv,
            const std::vector<std::string> &envd) {
    std::vector<std::string> args;
    args.push_back(prog);
    for (const auto &arg : argsv)
        args.push_back(arg);
    std::vector<std::string> env = envd;
    std::vector<char *> argv;
    for (auto &arg : args)
        argv.push_back(arg.data());
    argv.push_back(nullptr);
    std::vector<char *> envp;
    for (auto &item : env)
        envp.push_back(item.data());
    envp.push_back(nullptr);
    pid_t pid = fork();
    if (pid == -1)
        return -1;
    if (pid == 0) {
        execve(prog.c_str(), argv.data(), envp.data());
        _exit(127);
    }
    return static_cast<int>(pid);
}
